// Registers the private plugins checked out under plugins/local (a repo of
// your own, never this one; see docs/PLUGINS.md). Each folder there whose
// index.ts(x) exports `plugin` is one plugin, and its optional server.ts
// exporting `server` holds its server-only parts. Writes
// plugins/local.generated.ts and plugins/local-server.generated.ts (both
// gitignored; empty lists when there are none). Runs after install and
// before every build and dev server.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// The plugins folder; another can be given (for tests).
const plugins = process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), "..", "plugins");
const local = join(plugins, "local");

const found = existsSync(local)
  ? readdirSync(local, { withFileTypes: true })
      .filter((d) => d.isDirectory() && /^[a-z0-9-]+$/.test(d.name))
      .filter((d) => ["index.ts", "index.tsx"].some((f) => existsSync(join(local, d.name, f))))
      .map((d) => ({ name: d.name, server: existsSync(join(local, d.name, "server.ts")) }))
      .sort((a, b) => a.name.localeCompare(b.name))
  : [];

const header = "// Generated by scripts/local-plugins.mjs from plugins/local; don't edit.\n";

const client =
  header +
  'import type { FOQBPlugin } from "@/lib/plugins/types";\n' +
  found.map((p, i) => `import { plugin as p${i} } from "./local/${p.name}";\n`).join("") +
  `\nexport const localPlugins: FOQBPlugin[] = [${found.map((_, i) => `p${i}`).join(", ")}];\n`;

const withServer = found.map((p, i) => ({ ...p, i })).filter((p) => p.server);
const server =
  header +
  'import type { ServerPluginParts } from "@/lib/plugins/types";\n' +
  withServer
    .map((p) => `import { plugin as p${p.i} } from "./local/${p.name}";\nimport { server as s${p.i} } from "./local/${p.name}/server";\n`)
    .join("") +
  `\nexport const localServerParts: Record<string, ServerPluginParts> = {${withServer
    .map((p) => ` [p${p.i}.manifest.id]: s${p.i}`)
    .join(",")}${withServer.length ? " " : ""}};\n`;

// Only when changed, so a running dev server isn't sent a rebuild.
function write(file, content) {
  const path = join(plugins, file);
  if (!existsSync(path) || readFileSync(path, "utf8") !== content) writeFileSync(path, content);
}
write("local.generated.ts", client);
write("local-server.generated.ts", server);
if (found.length) console.log(`Private plugins: ${found.map((p) => p.name).join(", ")}`);
